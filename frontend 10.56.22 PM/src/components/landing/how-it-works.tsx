const panels = [SourcePanel, PlanPanel, PostPanel, ApprovePanel];

export function HowItWorks() {
  const [active, setActive] = useState(0);
  const Panel = panels[active];

  return (
    <section id="how-it-works" className="relative overflow-hidden bg-paper py-24 text-ink">
      <MosaicBackground />
      <div className="relative mx-auto max-w-6xl px-6">
        <p className="text-sm font-semibold uppercase tracking-widest text-brand">How it works</p>
        <h2 className="display mt-3 max-w-3xl text-[clamp(2rem,4vw,3.4rem)]">
          From one document to an approved campaign.
        </h2>

        <div className="mt-14 grid items-start gap-12 lg:grid-cols-[1fr_1.1fr]">
          <ul className="space-y-3">
            {site.steps.map((s, i) => {
              const on = i === active;
              return (
                <li key={s.title}>
                  <button
                    onClick={() => setActive(i)}
                    className={`w-full rounded-2xl border p-5 text-left transition-colors ${
                      on ? "border-brand bg-white shadow-md" : "border-line bg-white/40 hover:border-ink/30"
                    }`}
                  >
                    <div className="flex items-center gap-4">
                      <span
                        className={`grid h-9 w-9 shrink-0 place-items-center rounded-full text-sm font-bold ${
                          on ? "bg-brand text-white" : "bg-line"
                        }`}
                      >
                        {i + 1}
                      </span>
                      <span className="text-lg font-semibold">{s.title}</span>
                    </div>
                    {on && <p className="mt-3 pl-[52px] text-muted">{s.text}</p>}
                  </button>
                </li>
              );
            })}
          </ul>

          <div className="rounded-3xl border border-line bg-white p-6 shadow-xl">
            <AnimatePresence mode="wait">
              <motion.div
                key={active}
                initial={{ opacity: 0, y: 12 }}
                animate={{ opacity: 1, y: 0 }}
                exit={{ opacity: 0, y: -12 }}
                transition={{ duration: 0.2 }}
              >
                <Panel />
              </motion.div>
            </AnimatePresence>
          </div>
        </div>
      </div>
    </section>
  );
}